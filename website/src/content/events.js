export const statusMeta = {
  open: { label: 'Registration Open', tone: 'gold' },
  closing: { label: 'Closing Soon', tone: 'red' },
  upcoming: { label: 'Upcoming', tone: 'outline' },
  live: { label: 'Live', tone: 'red' },
  results: { label: 'Results Out', tone: 'green' },
  completed: { label: 'Completed', tone: 'muted' },
}

export const isUpcoming = (e) => ['upcoming', 'open', 'closing', 'live'].includes(e.status)

/** Upcoming soonest-first, then past events newest-first. */
export const sortedEvents = () => {
  const up = events.filter(isUpcoming).sort((a, b) => a.sortDate.localeCompare(b.sortDate))
  const past = events.filter((e) => !isUpcoming(e)).sort((a, b) => b.sortDate.localeCompare(a.sortDate))
  return [...up, ...past]
}

export const eventPath = (e) => `/events/${e.year}/${e.slug}`
export const findEvent = (year, slug) =>
  events.find((e) => String(e.year) === String(year) && e.slug === slug)
